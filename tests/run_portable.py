#!/usr/bin/env python
"""Prove the README's GDScript examples parse and run where the extension is NOT loaded.

The addon only has a Windows x86_64 library. On other platforms (or in an export that excludes
the addon) the LatencyUpscaling singleton does not exist, and a script that names it directly
does not parse. The READMEs therefore show guarded, dynamic access. This test runs the examples
exactly as they appear in README.md and addons/latency_upscaling/README.md.

    python tests/run_portable.py

Every ```gdscript block in both READMEs must be preceded by a marker line:
    <!-- portable-example -->       must parse and run in every configuration below
    <!-- windows-only-example -->   must run where the extension is loaded and must FAIL to parse
                                    where it is not (this is the control: it shows the test sees
                                    the difference, and it keeps the README's warning true)
A block without a marker fails the test, so no new example escapes it.

Configurations, each a fresh project under build/portable/:
  A extension loaded     the addon from this repository, as on Windows (headed run)
  B addon removed        no addons/ folder at all
  C no library           the addon present and listed, but its .gdextension has no library for
                         this platform: exactly what a Linux/macOS game sees (Godot prints its
                         "no library" error at start-up, which is the only error allowed)
  D export filter        a release export with the export preset's exclude filter
                         `addons/latency_upscaling/*`, run as an exported game
  E Linux export         a real Linux x86_64 export (not run: no Linux here), without and with the
                         filter: Godot must export it, warning about the missing library only
                         without the filter
Ends "portable test: <n> passed, <n> failed".
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNNER = ROOT / "tools" / "godot.py"
WORK = ROOT / "build" / "portable"
ADDON = ROOT / "addons" / "latency_upscaling"
READMES = [ROOT / "README.md", ADDON / "README.md"]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from log_scan import problems_in  # noqa: E402

# Godot's own start-up error for a listed extension without a library for this OS/architecture.
NO_LIBRARY = r"No GDExtension library found|GDExtension dynamic library not found|Failed to load GDExtension|Error loading extension"

PROJECT_GODOT = """config_version=5

[application]

config/name="LatencyUpscalingPortableTest"
run/main_scene="res://harness.tscn"
config/features=PackedStringArray("4.7", "Forward Plus")
"""

HARNESS_TSCN = """[gd_scene load_steps=2 format=3]

[ext_resource type="Script" path="res://harness.gd" id="1"]

[node name="Harness" type="Node"]
script = ExtResource("1")
"""

HARNESS_GD = """extends Node
## Generated by tests/run_portable.py: loads each README example, calls its public functions with
## sample arguments and prints one line "PORTABLE {...}", then quits.

const TARGETS := [%s]

var _frames := 0
var _examples := {}


func _ready() -> void:
	for path: String in TARGETS:
		var script: Script = load(path)
		if script == null or not script.can_instantiate():
			_examples[path] = null
			continue
		var node: Node = script.new()
		add_child(node)
		_examples[path] = node


func _process(_delta: float) -> void:
	_frames += 1
	if _frames < 30:
		return
	var out := {"singleton": Engine.has_singleton("LatencyUpscaling")}
	for path: String in TARGETS:
		var node: Node = _examples[path]
		if node == null:
			out[path] = {"loaded": false}
			continue
		var calls := {}
		for method: Dictionary in node.get_script().get_script_method_list():
			var method_name: String = method["name"]
			if method_name.begins_with("_"):
				continue
			var args := []
			for arg: Dictionary in method["args"]:
				args.append(_sample(arg["type"]))
			calls[method_name] = str(node.callv(method_name, args))
		out[path] = {"loaded": true, "calls": calls}
	if out["singleton"]:
		out["reflex_mode"] = Engine.get_singleton("LatencyUpscaling").get("reflex_mode")
	print("PORTABLE " + JSON.stringify(out))
	get_tree().quit()


static func _sample(type: int) -> Variant:
	match type:
		TYPE_INT:
			return 2
		TYPE_FLOAT:
			return 0.0
		TYPE_BOOL:
			return false
		TYPE_STRING:
			return ""
	return null
"""

PRESET = """[preset.0]

name="Windows Desktop"
platform="Windows Desktop"
runnable=true
export_filter="all_resources"
include_filter=""
exclude_filter="addons/latency_upscaling/*"
export_path="out/game.exe"

[preset.0.options]

debug/export_console_wrapper=2
binary_format/embed_pck=false
binary_format/architecture="x86_64"
codesign/enable=false
"""


LINUX_PRESETS = """[preset.0]

name="Linux"
platform="Linux"
runnable=false
export_filter="all_resources"
include_filter=""
exclude_filter=""
export_path="out_plain/game.x86_64"

[preset.0.options]

binary_format/embed_pck=false
binary_format/architecture="x86_64"

[preset.1]

name="Linux filtered"
platform="Linux"
runnable=false
export_filter="all_resources"
include_filter=""
exclude_filter="addons/latency_upscaling/*"
export_path="out_filtered/game.x86_64"

[preset.1.options]

binary_format/embed_pck=false
binary_format/architecture="x86_64"
"""


def extract_examples() -> tuple[list[str], list[str], list[str]]:
    """(portable blocks, windows-only blocks, unmarked block descriptions)."""
    portable, windows_only, unmarked = [], [], []
    for readme in READMES:
        lines = readme.read_text(encoding="utf-8").splitlines()
        i = 0
        while i < len(lines):
            if lines[i].strip() == "```gdscript":
                j = i + 1
                while lines[j].strip() != "```":
                    j += 1
                code = "\n".join(lines[i + 1:j]) + "\n"
                k = i - 1
                while k >= 0 and not lines[k].strip():
                    k -= 1
                marker = lines[k].strip() if k >= 0 else ""
                if marker == "<!-- portable-example -->":
                    portable.append(code)
                elif marker == "<!-- windows-only-example -->":
                    windows_only.append(code)
                else:
                    unmarked.append(f"{readme.relative_to(ROOT)}:{i + 1}")
                i = j
            i += 1
    return portable, windows_only, unmarked


def godot(project: Path, args: list[str], log: str, timeout: int = 300) -> tuple[int, str]:
    cmd = [sys.executable, str(RUNNER), "--project", str(project), "--timeout", str(timeout), "--log", log] + args
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return p.returncode, p.stdout + p.stderr


def run_exported(exe: Path) -> tuple[int, str]:
    proc = subprocess.Popen([str(exe), "--headless", "--quit-after", "600"], cwd=str(exe.parent), stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace")
    try:
        out, _ = proc.communicate(timeout=120)
    except subprocess.TimeoutExpired:
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(proc.pid)], capture_output=True)
        out, _ = proc.communicate()
        return 124, out
    return proc.returncode, out


def make_project(name: str, examples: dict[str, str], with_addon: bool) -> Path:
    project = WORK / name
    if project.exists():
        shutil.rmtree(project)
    project.mkdir(parents=True)
    (project / "project.godot").write_text(PROJECT_GODOT, encoding="utf-8")
    (project / "harness.tscn").write_text(HARNESS_TSCN, encoding="utf-8")
    for file_name, code in examples.items():
        (project / file_name).write_text(code, encoding="utf-8")
    if with_addon:
        shutil.copytree(ADDON, project / "addons" / "latency_upscaling",
                        ignore=shutil.ignore_patterns("*.lib", "*.exp", "*.pdb", "~*"))
    return project


def set_targets(project: Path, targets: list[str]) -> None:
    listing = ", ".join(f'"res://{t}"' for t in targets)
    (project / "harness.gd").write_text(HARNESS_GD % listing, encoding="utf-8")


def portable_line(out: str) -> dict:
    for line in out.splitlines():
        if line.startswith("PORTABLE "):
            return json.loads(line[len("PORTABLE "):])
    return {}


def main() -> int:
    passed = failed = 0

    def check(name: str, ok: bool, detail: str) -> None:
        nonlocal passed, failed
        print(f"{'PASS' if ok else 'FAIL'}  {name}  ({detail})", flush=True)
        passed += ok
        failed += not ok

    portable, windows_only, unmarked = extract_examples()
    check("every README gdscript example is marked portable or windows-only", not unmarked and bool(portable) and bool(windows_only),
          f"{len(portable)} portable, {len(windows_only)} windows-only" + (f"; unmarked: {', '.join(unmarked)}" if unmarked else ""))
    examples = {f"ex_portable_{i + 1}.gd": c for i, c in enumerate(portable)}
    examples.update({f"ex_windows_only_{i + 1}.gd": c for i, c in enumerate(windows_only)})
    portable_files = [f for f in examples if f.startswith("ex_portable")]
    windows_files = [f for f in examples if f.startswith("ex_windows_only")]

    def all_ran(result: dict, files: list[str]) -> bool:
        return all(result.get(f"res://{f}", {}).get("loaded") for f in files)

    def describe(result: dict, problems: list[str]) -> str:
        if not result:
            return "no PORTABLE line" + (f"; {problems[0]}" if problems else "")
        text = f"singleton={result.get('singleton')}"
        if "reflex_mode" in result:
            text += f" reflex_mode={result['reflex_mode']}"
        return text + (f"; {problems[0]}" if problems else "")

    # A: extension loaded (Windows).
    project = make_project("A_loaded", examples, with_addon=True)
    godot(project, ["--headless", "--import"], "portable_A_import")
    set_targets(project, portable_files)
    code, out = godot(project, ["--quit-after", "600"], "portable_A_portable")
    result, problems = portable_line(out), problems_in(out)
    check("A extension loaded: portable examples run and reach the singleton",
          code == 0 and not problems and all_ran(result, portable_files) and result.get("singleton") is True
          and result.get("reflex_mode") == 2, describe(result, problems))
    set_targets(project, windows_files)
    code, out = godot(project, ["--headless", "--quit-after", "600"], "portable_A_windows_only")
    result, problems = portable_line(out), problems_in(out)
    check("A extension loaded: the windows-only example runs too",
          code == 0 and not problems and all_ran(result, windows_files) and result.get("reflex_mode") == 2,
          describe(result, problems))

    # B: addon removed.
    project = make_project("B_removed", examples, with_addon=False)
    set_targets(project, portable_files)
    code, out = godot(project, ["--headless", "--quit-after", "600"], "portable_B_portable")
    result, problems = portable_line(out), problems_in(out)
    check("B addon removed: portable examples parse and run without errors",
          code == 0 and not problems and all_ran(result, portable_files) and result.get("singleton") is False,
          describe(result, problems))
    set_targets(project, windows_files)
    code, out = godot(project, ["--headless", "--quit-after", "600"], "portable_B_windows_only")
    result = portable_line(out)
    parse_error = re.search(r'Identifier "LatencyUpscaling" not declared', out) is not None
    check("B control: the windows-only example fails to parse without the extension",
          parse_error and bool(result) and not any(result.get(f"res://{f}", {}).get("loaded") for f in windows_files),
          "parse error reported" if parse_error else "NO parse error: the test could not tell portable from non-portable code")

    # C: no library for this platform (Linux/macOS as seen by the game).
    project = make_project("C_no_library", examples, with_addon=True)
    godot(project, ["--headless", "--import"], "portable_C_import")  # lists the extension, as the editor would
    gdext = project / "addons" / "latency_upscaling" / "latency_upscaling.gdextension"
    gdext.write_text("\n".join(l for l in gdext.read_text(encoding="utf-8").splitlines()
                               if not l.startswith("windows.")) + "\n", encoding="utf-8")
    set_targets(project, portable_files)
    code, out = godot(project, ["--headless", "--quit-after", "600"], "portable_C_portable")
    result, problems = portable_line(out), problems_in(out, [NO_LIBRARY])
    no_library = [l.strip() for l in out.splitlines() if re.search(NO_LIBRARY, l)]
    check("C no library for the platform: Godot reports it, examples still run",
          code == 0 and not problems and bool(no_library) and all_ran(result, portable_files) and result.get("singleton") is False,
          describe(result, problems) + (f"; Godot says: {no_library[0]}" if no_library else "; Godot printed no library error"))

    # D: release export with the addon excluded by the export filter.
    project = make_project("D_export_filter", examples, with_addon=True)
    (project / "export_presets.cfg").write_text(PRESET, encoding="utf-8")
    godot(project, ["--headless", "--import"], "portable_D_import")
    set_targets(project, portable_files)
    (project / "out").mkdir()
    code, out = godot(project, ["--headless", "--export-release", "Windows Desktop", "out/game.exe"], "portable_D_export", timeout=400)
    dlls = sorted(p.name for p in (project / "out").glob("*.dll"))
    check("D export filter: the export contains no addon library", code == 0 and not dlls,
          f"exit {code}; DLLs: {', '.join(dlls) or 'none'}")
    exe = project / "out" / "game.console.exe"
    code, out = run_exported(exe if exe.exists() else project / "out" / "game.exe")
    result, problems = portable_line(out), problems_in(out)
    loader_errors = [l.strip() for l in out.splitlines() if re.search(NO_LIBRARY, l)]
    check("D export filter: exported game runs the examples with no GDExtension error",
          code == 0 and not problems and not loader_errors and all_ran(result, portable_files) and result.get("singleton") is False,
          describe(result, problems + loader_errors))

    # E: real Linux exports, without and with the exclude filter (built, not run).
    project = make_project("E_linux_export", examples, with_addon=True)
    (project / "export_presets.cfg").write_text(LINUX_PRESETS, encoding="utf-8")
    godot(project, ["--headless", "--import"], "portable_E_import")
    set_targets(project, portable_files)
    for preset, label in (("Linux", "without the filter"), ("Linux filtered", "with the filter")):
        out_dir = project / ("out_plain" if preset == "Linux" else "out_filtered")
        out_dir.mkdir()
        code, out = godot(project, ["--headless", "--export-release", preset, f"{out_dir.name}/game.x86_64"],
                          f"portable_E_{out_dir.name}", timeout=400)
        warning = [l.strip() for l in out.splitlines() if re.search(r'No "x86_64" library found for GDExtension', l)]
        exported = (out_dir / "game.x86_64").exists() and (out_dir / "game.pck").exists()
        expect_warning = preset == "Linux"
        check(f"E Linux export {label}: exported" + (", Godot warns about the missing library" if expect_warning else ", no warning"),
              code == 0 and exported and bool(warning) == expect_warning,
              f"exit {code}, files {'present' if exported else 'MISSING'}"
              + (f"; Godot says: {warning[0]}" if warning else "; no library warning"))

    print(f"\nportable test: {passed} passed, {failed} failed")
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
